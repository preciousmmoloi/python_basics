
# VARIABLES - values are stored to names which become their containers

#Calculate BMI
height = 1.79
weight = 68.7

bmi = weight / (height ** 2)
print(round(bmi, 2))

# TYPES - all values stored in variables have types --> Operators behave differently for different data types

print(type(bmi)) #float - has a integer and fraction parts
print(type('Hello')) #str - text - use double nd single quotes
print(type("23" + "1")) #str 
print(type(23)) #integer - int
print(type(True)) #boolean - bool- Capitalized


